const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {seal} = require('./encrypt-journey.cjs');
const {decryptJourney} = require('../journey-crypto.js');
(async () => {
  const fixture = {journey: require('./fixtures/journey.cjs'), places: []};
  const password = 'local-ui-test-only-123';
  const sealed = seal(fixture, password);
  assert.deepEqual(await decryptJourney(sealed, password), fixture);
  await assert.rejects(decryptJourney(sealed, 'wrong-password'));
  const damaged = structuredClone(sealed);
  const bytes = Buffer.from(damaged.ciphertext, 'base64'); bytes[0] ^= 1;
  damaged.ciphertext = bytes.toString('base64');
  await assert.rejects(decryptJourney(damaged, password));
  assert.notEqual(seal(fixture, password).ciphertext, sealed.ciphertext);
  const source = fs.readFileSync('owner-globe.js', 'utf8');
  assert(!source.includes("fetch('journey.json") && !source.includes("fetch('places.json"));
  const privateDir = path.join(os.homedir(), 'Documents/Codex-private/subright-journey');
  const actualPassword = fs.readFileSync(path.join(privateDir, 'website-password.txt'), 'utf8').trim();
  const envelope = JSON.parse(fs.readFileSync('journey.enc.json'));
  const payload = await decryptJourney(envelope, actualPassword);
  assert.deepEqual(payload.journey, JSON.parse(fs.readFileSync(path.join(privateDir, 'journey.json'))));
  assert.deepEqual(payload.places, JSON.parse(fs.readFileSync(path.join(privateDir, 'places.json'))));
  assert(!fs.readFileSync('journey.enc.json', 'utf8').includes(actualPassword));
  fs.writeFileSync('/tmp/subright-journey-ui-fixture.json', JSON.stringify(sealed));
  console.log('Encryption: Web Crypto round-trip, wrong password, tampering, randomization, and complete owner data passed.');
})();
